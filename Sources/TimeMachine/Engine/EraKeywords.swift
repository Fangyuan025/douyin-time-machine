    static func key(_ ym: YearMonth) -> String { String(format: "%04d-%02d", ym.year, ym.month) }

    /// 时间段内值得直接翻话题页的热点词（当月热点 + 疫情三年的通用词）
    static func topicTerms(for window: TimeWindow) -> [String] {
        var out: [String] = []
        for idx in window.monthIndices { out += byMonth[key(YearMonth(index: idx))] ?? [] }
        if window.monthIndices.overlaps(pandemicMonths) { out += pandemicTerms }
        var seen = Set<String>()
        return out.filter { !weakTerms.contains($0) && seen.insert($0).inserted }
    }

    /// 某个月（含前后各一个月的余温）的热点词，用于排序时判断“时代感”
    static func terms(forMonth index: Int) -> [String] {
        var out: [String] = []
        for d in [0, -1, 1] {
            out += byMonth[key(YearMonth(index: index + d))] ?? []
        }
        if pandemicMonths.contains(index) { out += pandemicTerms }
        return out
    }

    /// 为时间段生成搜索词：只用标志性热点（季节、节日、生肖这类泛词不浪费宝贵的搜索次数），
    /// 各月轮流取，每个月内按时间线里的顺序（越靠前越标志性）
    static func keywords(for window: TimeWindow) -> [String] {
        var monthly: [[String]] = window.monthIndices.map {
            (byMonth[key(YearMonth(index: $0))] ?? []).filter { !weakTerms.contains($0) }
        }
        var ordered: [String] = []
        while monthly.contains(where: { !$0.isEmpty }) {
            for i in monthly.indices where !monthly[i].isEmpty {
                ordered.append(monthly[i].removeFirst())
            }
        }
        var seen = Set<String>()
        return ordered.filter { seen.insert($0).inserted }
    }
