    /// 热点词所属的主题：疫情相关的词都归到“疫情”，其他词各自成主题
    static func theme(of term: String) -> String {
        let t = term.hasPrefix("#") ? String(term.dropFirst()) : term
        return pandemicTheme.contains(t) || pandemicTerms.contains(where: { t.contains($0) }) ? "疫情" : t
    }

