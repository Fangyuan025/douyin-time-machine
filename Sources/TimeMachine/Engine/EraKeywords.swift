    static func keywords(for window: TimeWindow) -> [String] {
        var list: [String] = []
        for y in window.years {
            list += byYear[y] ?? []
            list.append("\(y)年")
        }
        if window.from == window.to {
            list.append("\(window.from.year)年\(window.from.month)月")
        }
        return list
    }
