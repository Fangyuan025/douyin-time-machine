    /// 文本是否真正命中某个热点词（考虑歧义词的上下文）
    static func matches(_ term: String, in text: String) -> Bool {
        guard text.localizedCaseInsensitiveContains(term) else { return false }
        guard let ctx = contextual[term] else { return true }
        return ctx.contains { text.contains($0) }
    }

